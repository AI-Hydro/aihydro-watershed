"""
Pinned, hash-verified acquisition of per-region MERIT-Basins / MERIT-Hydro files.

The manifest (``delineator_data_manifest.json``, generated by ``scripts/gen_delineator_manifest.py``) pins every
file served by mghydro.com for the ``delineator`` package (v2.2.4, data version v3) by SHA-256 and size. Nothing is
installed or trusted unless its digest matches; a mismatch raises :class:`AssetIntegrityError` (fail closed).

Download mechanics:

* One writer per destination: a lock file, plus a ``mkstemp`` partial file in the destination directory.
* An interrupted partial file is resumed with an HTTP ``Range`` request when the server answers 206; otherwise it
  restarts from zero.
* A completed download that fails verification is deleted, and a negative-cache marker refuses automatic retries for
  ``NEGATIVE_CACHE_SECONDS`` (24 h) so a bad mirror is not hammered. ``force=True`` overrides it.

The level-2 (megabasin) index is the one file mghydro.com does not serve. It is pinned by the git blob SHA-1 at the
delineator v2.2.4 tag commit, and the SHA-256 of the first verified copy is recorded in the provenance sidecar and
enforced afterwards.
"""

from __future__ import annotations

import glob
import hashlib
import json
import logging
import os
import tempfile
import time
import urllib.request
from dataclasses import dataclass
from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path
from typing import IO, Any, Callable

log = logging.getLogger(__name__)

_MANIFEST_PATH = Path(__file__).parent / "delineator_data_manifest.json"
_CHUNK = 1024 * 1024
VALID_KINDS = ("basins", "rivers", "flowdir", "accum")
NEGATIVE_CACHE_SECONDS = 24 * 3600
# Files below this size, and the level-2 index, are always re-hashed on use (cheap, and immune to a tamper that
# restores mtime). Larger rasters rely on the sidecar's size/mtime/inode/ctime fast path.
REHASH_BELOW_BYTES = 200_000_000
_LOCK_STALE_SECONDS = 6 * 3600
_LOCK_POLL_SECONDS = 0.2


class AssetIntegrityError(RuntimeError):
    """A MERIT data file does not match its pinned digest or size (fail closed)."""

    code = "MERIT_ASSET_INTEGRITY_FAILED"

    def __init__(self, message: str):
        super().__init__(f"{self.code}: {message}")


@dataclass(frozen=True)
class AssetSpec:
    name: str
    url: str
    size_bytes: int | None
    sha256: str | None
    git_blob_sha1: str | None = None


@lru_cache(maxsize=1)
def load_manifest() -> dict[str, Any]:
    return json.loads(_MANIFEST_PATH.read_text(encoding="utf-8"))


def licence_summary() -> str:
    return str(load_manifest()["licence"]["summary"])


def mirror_base_url() -> str:
    """Optional lab mirror (``AIHYDRO_MERIT_BASE_URL``); files are still hash-verified."""
    return os.environ.get("AIHYDRO_MERIT_BASE_URL", "").rstrip("/")


def asset_spec(name: str) -> AssetSpec:
    man = load_manifest()
    mirror = mirror_base_url()
    lvl2 = man["level2_index"]
    if name == lvl2["name"]:
        url = f"{mirror}/{name}" if mirror else lvl2["url"]
        return AssetSpec(name, url, lvl2["size_bytes"], lvl2.get("sha256"), lvl2.get("git_blob_sha1"))
    entry = man["files"].get(name)
    if entry is None:
        raise KeyError(f"{name} is not in the pinned MERIT data manifest.")
    base = mirror or man["source"]["base_url"].rstrip("/")
    return AssetSpec(name, f"{base}/{name}", entry["size_bytes"], entry["sha256"])


def region_asset_name(kind: str, pfaf: str) -> str:
    if kind not in VALID_KINDS:
        raise ValueError(f"kind must be one of {VALID_KINDS}")
    ext = "db" if kind in ("basins", "rivers") else "tif"
    return f"{kind}{str(int(pfaf)).zfill(2)}.{ext}"


def region_asset_spec(kind: str, pfaf: str) -> AssetSpec:
    return asset_spec(region_asset_name(kind, pfaf))


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(_CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def git_blob_sha1_file(path: Path) -> str:
    size = Path(path).stat().st_size
    h = hashlib.sha1(f"blob {size}\0".encode())
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(_CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


# ------------------------------------------------------------------------------ provenance sidecar


def sidecar_path(path: Path) -> Path:
    return path.with_name(path.name + ".provenance.json")


def _write_sidecar(path: Path, spec: AssetSpec, sha256: str, *, source: str) -> dict[str, Any]:
    st = path.stat()
    man = load_manifest()
    rec = {
        "name": spec.name,
        "sha256": sha256,
        "size_bytes": st.st_size,
        "mtime_ns": st.st_mtime_ns,
        "ctime_ns": st.st_ctime_ns,
        "ino": st.st_ino,
        "url": spec.url,
        "pinned_sha256": spec.sha256,
        "pinned_git_blob_sha1": spec.git_blob_sha1,
        "source": source,
        "data_version": man["source"]["data_version"],
        "delineator_version": man["source"]["package_version"],
        "licence": man["licence"]["summary"],
        "verified_at": datetime.now(timezone.utc).isoformat(),
    }
    sidecar_path(path).write_text(json.dumps(rec, indent=2), encoding="utf-8")
    return rec


def _read_sidecar(path: Path) -> dict[str, Any] | None:
    sc = sidecar_path(path)
    if not sc.exists():
        return None
    try:
        return json.loads(sc.read_text(encoding="utf-8"))
    except Exception:
        return None


def read_provenance(path: Path) -> dict[str, Any] | None:
    """The verification record written when ``path`` was verified, if any."""
    return _read_sidecar(Path(path))


def verify_file(path: Path, spec: AssetSpec, *, source: str = "local_file") -> dict[str, Any]:
    """Hash ``path`` against ``spec`` and write the provenance sidecar; raise on any mismatch."""
    path = Path(path)
    size = path.stat().st_size
    if spec.size_bytes is not None and size != spec.size_bytes:
        raise AssetIntegrityError(
            f"{path.name} is {size} bytes; the pinned manifest says {spec.size_bytes}. "
            "Delete it and re-stage."
        )
    digest = sha256_file(path)
    if spec.sha256 is not None:
        if digest != spec.sha256:
            raise AssetIntegrityError(
                f"{path.name} SHA-256 {digest[:16]}... does not match the pinned {spec.sha256[:16]}.... "
                "Delete it and re-stage."
            )
    else:
        prior = _read_sidecar(path)
        if prior and prior.get("sha256") and prior["sha256"] != digest:
            raise AssetIntegrityError(
                f"{path.name} changed since it was first verified (SHA-256 differs from its provenance record)."
            )
        if spec.git_blob_sha1 is not None and git_blob_sha1_file(path) != spec.git_blob_sha1:
            raise AssetIntegrityError(
                f"{path.name} git blob SHA-1 does not match the pin for the delineator release tag."
            )
    return _write_sidecar(path, spec, digest, source=source)


def _always_rehash(path: Path, size: int) -> bool:
    return path.name == load_manifest()["level2_index"]["name"] or (
        path.suffix == ".db" and size < REHASH_BELOW_BYTES
    )


def verified_path(path: Path, spec: AssetSpec) -> Path | None:
    """Return ``path`` if it exists and verifies; ``None`` if absent; raise if present but wrong.

    Small databases and the level-2 index are re-hashed on every use. For larger files a matching sidecar
    (same size, mtime, ctime and inode) avoids re-hashing; ``ctime`` cannot be restored by ``utime``, so an
    in-place edit that keeps the size and mtime still forces a re-hash.
    """
    path = Path(path)
    if not path.exists():
        return None
    st = path.stat()
    rec = _read_sidecar(path)
    if (
        not _always_rehash(path, st.st_size)
        and rec
        and rec.get("sha256")
        and rec.get("size_bytes") == st.st_size
        and rec.get("mtime_ns") == st.st_mtime_ns
        and rec.get("ctime_ns") == st.st_ctime_ns
        and rec.get("ino") == st.st_ino
        and (spec.sha256 is None or rec.get("sha256") == spec.sha256)
    ):
        return path
    verify_file(path, spec, source=(rec or {}).get("source", "local_file"))
    return path


# --------------------------------------------------------------------- negative cache + lock


def integrity_marker_path(dest: Path) -> Path:
    return dest.with_name(dest.name + ".integrity-failed.json")


def active_integrity_marker(dest: Path) -> dict[str, Any] | None:
    """The negative-cache record for ``dest`` if a failed download happened within the last 24 h."""
    mp = integrity_marker_path(Path(dest))
    if not mp.exists():
        return None
    try:
        rec = json.loads(mp.read_text(encoding="utf-8"))
    except Exception:
        return None
    if time.time() - float(rec.get("epoch", 0)) >= NEGATIVE_CACHE_SECONDS:
        return None
    return rec


def marker_message(rec: dict[str, Any]) -> str:
    until = datetime.fromtimestamp(float(rec["epoch"]) + NEGATIVE_CACHE_SECONDS, timezone.utc).isoformat()
    obs = rec.get("observed_sha256") or "n/a"
    return (
        f"{rec['file']} failed verification at {rec['time']} (observed SHA-256 {obs[:16]}..., "
        f"expected {str(rec.get('expected_sha256'))[:16]}...); automatic retry is refused until {until}. "
        f"Delete {integrity_marker_path(Path(rec['dest'])).name} to retry sooner."
    )


def _write_marker(dest: Path, spec: AssetSpec, observed: str | None, reason: str) -> None:
    now = time.time()
    integrity_marker_path(dest).write_text(
        json.dumps(
            {
                "file": spec.name,
                "dest": str(dest),
                "url": spec.url,
                "observed_sha256": observed,
                "expected_sha256": spec.sha256,
                "expected_git_blob_sha1": spec.git_blob_sha1,
                "reason": reason,
                "time": datetime.fromtimestamp(now, timezone.utc).isoformat(),
                "epoch": now,
            },
            indent=2,
        ),
        encoding="utf-8",
    )


class _Lock:
    """Cross-platform exclusive lock file (``O_EXCL``), broken only when stale."""

    def __init__(self, path: Path, timeout: float = 3600.0):
        self.path, self.timeout, self.fd = path, timeout, None

    def __enter__(self):
        deadline = time.time() + self.timeout
        while True:
            try:
                self.fd = os.open(self.path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(self.fd, str(os.getpid()).encode())
                return self
            except FileExistsError:
                try:
                    if time.time() - self.path.stat().st_mtime > _LOCK_STALE_SECONDS:
                        self.path.unlink(missing_ok=True)
                        continue
                except FileNotFoundError:
                    continue
                if time.time() > deadline:
                    raise TimeoutError(f"timed out waiting for {self.path.name}") from None
                time.sleep(_LOCK_POLL_SECONDS)

    def __exit__(self, *exc):
        if self.fd is not None:
            os.close(self.fd)
        self.path.unlink(missing_ok=True)


# --------------------------------------------------------------------------------- download

Opener = Callable[..., IO[bytes]]


def _default_opener(url: str, headers: dict[str, str] | None = None) -> IO[bytes]:
    req = urllib.request.Request(url, headers=headers or {})
    return urllib.request.urlopen(req, timeout=300)  # noqa: S310


def _is_partial(resp: Any) -> bool:
    status = getattr(resp, "status", None) or getattr(resp, "code", None)
    return status == 206


def fetch_verified(
    spec: AssetSpec,
    dest: Path,
    *,
    opener: Opener | None = None,
    progress_cb: Callable[[int, int], None] | None = None,
    force: bool = False,
) -> Path:
    """Stream ``spec.url`` to ``dest``, installing it only if size and digest match the pin."""
    if spec.sha256 is None and spec.git_blob_sha1 is None:
        raise AssetIntegrityError(f"{spec.name} has no pinned digest; refusing to download.")
    if spec.size_bytes is None:
        raise AssetIntegrityError(f"{spec.name} has no pinned size; refusing to download.")
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    if not force:
        rec = active_integrity_marker(dest)
        if rec:
            raise AssetIntegrityError(marker_message(rec))
    open_ = opener or _default_opener
    with _Lock(dest.with_name(dest.name + ".lock")):
        # Another process may have finished while we waited for the lock.
        try:
            done = verified_path(dest, spec)
        except AssetIntegrityError:
            done = None
        if done is not None:
            return done
        parts = sorted(glob.glob(str(dest.parent / f"{dest.name}.*.part")), key=os.path.getmtime)
        part = Path(parts[-1]) if parts else None
        for extra in parts[:-1]:
            Path(extra).unlink(missing_ok=True)
        if part is None:
            fd, name = tempfile.mkstemp(prefix=f"{dest.name}.", suffix=".part", dir=dest.parent)
            os.close(fd)
            part = Path(name)
        try:
            digest = _download_into(part, spec, open_, progress_cb)
        except AssetIntegrityError as exc:
            part.unlink(missing_ok=True)
            _write_marker(dest, spec, getattr(exc, "observed", None), str(exc))
            raise
        except BaseException:
            # Network errors keep the partial file so the next call can resume it.
            raise
        os.replace(part, dest)
        integrity_marker_path(dest).unlink(missing_ok=True)
        _write_sidecar(dest, spec, digest, source=spec.url)
    return dest


def _download_into(
    part: Path,
    spec: AssetSpec,
    open_: Opener,
    progress_cb: Callable[[int, int], None] | None,
) -> str:
    size = spec.size_bytes or 0
    have = part.stat().st_size if part.exists() else 0
    if have > size:
        have = 0
    sha = hashlib.sha256()
    blob = hashlib.sha1(f"blob {size}\0".encode())
    resp = open_(spec.url, {"Range": f"bytes={have}-"}) if have else open_(spec.url)
    with resp as r:
        if have and _is_partial(r):
            with part.open("rb") as f:  # re-hash what we already have
                for chunk in iter(lambda: f.read(_CHUNK), b""):
                    sha.update(chunk)
                    blob.update(chunk)
            mode = "ab"
        else:
            have, mode = 0, "wb"
        got = have
        with part.open(mode) as out:
            while True:
                chunk = r.read(_CHUNK)
                if not chunk:
                    break
                out.write(chunk)
                sha.update(chunk)
                blob.update(chunk)
                got += len(chunk)
                if got > size:
                    raise _mismatch(spec, None, f"received more than the pinned {size} bytes")
                if progress_cb:
                    progress_cb(got, size)
    if got != size:
        if got < size:
            raise ConnectionError(f"{spec.name}: connection ended at {got} of {size} bytes (partial file kept)")
        raise _mismatch(spec, sha.hexdigest(), f"got {got} bytes, pinned size is {size}")
    digest = sha.hexdigest()
    if spec.sha256 is not None and digest != spec.sha256:
        raise _mismatch(spec, digest, f"SHA-256 {digest[:16]}... does not match the pinned {spec.sha256[:16]}...")
    if spec.sha256 is None and blob.hexdigest() != spec.git_blob_sha1:
        raise _mismatch(spec, digest, "git blob SHA-1 does not match the release-tag pin")
    return digest


def _mismatch(spec: AssetSpec, observed: str | None, why: str) -> AssetIntegrityError:
    exc = AssetIntegrityError(f"{spec.name}: {why}.")
    exc.observed = observed  # type: ignore[attr-defined]
    return exc
